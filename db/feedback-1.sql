-- Колія: обратная связь (форма на сайте → таблица feedback → вкладка «Обращения» в админке)
-- Выполнить в Supabase → SQL Editor ДО слияния изменений в main. Повторный запуск безопасен.
-- Анонимный посетитель может только добавить строку: читать, менять и удалять обращения могут только вы (вошедший в админку).
begin;

create table if not exists public.feedback (
    id         bigint generated by default as identity primary key,
    created_at timestamptz not null default now(),
    kind       text not null default 'other' check (kind in ('data', 'idea', 'question', 'other')),
    message    text not null check (char_length(btrim(message)) between 5 and 2000),
    contact    text not null default '' check (char_length(contact) <= 200),
    page       text not null default '' check (char_length(page) <= 300),
    lang       text not null default '' check (char_length(lang) <= 5),
    status     text not null default 'new' check (status in ('new', 'done')),
    note       text not null default '' check (char_length(note) <= 2000)
);

alter table public.feedback enable row level security;
drop policy if exists feedback_insert on public.feedback;
drop policy if exists feedback_admin  on public.feedback;
-- anon: только добавление, и только «новых» обращений без заметки (status/note нельзя подсунуть через API)
create policy feedback_insert on public.feedback for insert to anon, authenticated
    with check (status = 'new' and note = '');
create policy feedback_admin on public.feedback to authenticated using (true) with check (true);

revoke all on public.feedback from anon;
grant insert on public.feedback to anon;
grant select, insert, update, delete on public.feedback to authenticated;

create index if not exists feedback_status_created_idx on public.feedback (status, created_at desc);

select count(*) as feedback_rows from public.feedback;
commit;

create table if not exists public.home_links (
    id        integer generated by default as identity primary key,
    kind      text    not null check (kind in ('phone', 'buy', 'airport')),
    sort      integer not null default 0,
    label_ru  text    not null check (btrim(label_ru) <> ''),
    label_uk  text    not null default '',
    label_en  text    not null default '',
    label_pl  text    not null default '',
    url       text    not null default '' check (url = '' or url ~ '^https?://'),
    active    boolean not null default true
);

alter table public.home_links enable row level security;
drop policy if exists home_links_read on public.home_links;
drop policy if exists home_links_write on public.home_links;
